package main

import (
	"fmt"
	"strings"

	"github.com/galihanggara68/foundation/pkg/emitterkit"
)

func main() {
	emitterkit.RunPlugin(generatePythonFastAPI)
}

func generatePythonFastAPI(req emitterkit.GenerationRequest) (emitterkit.GenerationResponse, error) {
	resp := emitterkit.GenerationResponse{
		Files:       make(map[string]string),
		TestCommand: "pytest",
	}

	if req.SemanticIR == nil {
		return resp, nil
	}

	entities := req.SemanticIR.Entities
	actions := req.SemanticIR.Actions

	// Consume the compiler-owned pagination policy rather than inventing one.
	var page *emitterkit.PaginationDefaults
	if req.Platform != nil {
		page = &req.Platform.Pagination
	}

	resp.Files["models.py"] = emitModelsPy(entities)
	resp.Files["repository.py"] = emitRepositoryPy(entities, page)
	resp.Files["main.py"] = emitMainPy(entities, actions)
	resp.Files["test_app.py"] = emitTestAppPy(entities, actions)

	return resp, nil
}

func emitModelsPy(entities []emitterkit.EntityDecl) string {
	var sb strings.Builder
	sb.WriteString(`# Generated by foundation-gen-python-fastapi. DO NOT EDIT.
try:
    from pydantic import BaseModel, Field
except ImportError:
    class BaseModel:
        def __init__(self, **kwargs):
            for k, v in kwargs.items():
                setattr(self, k, v)
        def model_dump(self):
            return dict(self.__dict__)
        def dict(self):
            return dict(self.__dict__)

from typing import Optional, List, Dict, Any

`)

	for _, e := range entities {
		sb.WriteString(fmt.Sprintf("class %s(BaseModel):\n", e.Name))
		if len(e.Fields) == 0 {
			sb.WriteString("    pass\n\n")
			continue
		}
		for _, f := range e.Fields {
			pType := pyType(f.Type)
			if f.Optional {
				sb.WriteString(fmt.Sprintf("    %s: Optional[%s] = None\n", f.Name, pType))
			} else {
				sb.WriteString(fmt.Sprintf("    %s: %s\n", f.Name, pType))
			}
		}
		sb.WriteString("\n")
	}

	return sb.String()
}

func emitRepositoryPy(entities []emitterkit.EntityDecl, page *emitterkit.PaginationDefaults) string {
	var sb strings.Builder
	sb.WriteString(`# In-memory repository implementation for entities
from typing import Dict, List, Optional
from models import *

`)

	if page != nil {
		sb.WriteString(fmt.Sprintf(`# Platform pagination policy (compiler-owned).
DEFAULT_PAGE_LIMIT = %d
MAX_PAGE_LIMIT = %d

`, page.DefaultLimit, page.MaxLimit))
	}

	for _, e := range entities {
		idField := "id"
		if len(e.Fields) > 0 {
			idField = e.Fields[0].Name
			for _, f := range e.Fields {
				if f.Name == "id" {
					idField = "id"
					break
				}
			}
		}

		sb.WriteString(fmt.Sprintf("class %sRepository:\n", e.Name))
		sb.WriteString("    def __init__(self):\n")
		sb.WriteString(fmt.Sprintf("        self._items: Dict[str, %s] = {}\n\n", e.Name))

		sb.WriteString(fmt.Sprintf("    def save(self, entity: %s) -> %s:\n", e.Name, e.Name))
		sb.WriteString(fmt.Sprintf("        key = str(getattr(entity, %q, ''))\n", idField))
		sb.WriteString("        self._items[key] = entity\n")
		sb.WriteString("        return entity\n\n")

		sb.WriteString(fmt.Sprintf("    def find_by_id(self, item_id: str) -> Optional[%s]:\n", e.Name))
		sb.WriteString("        return self._items.get(str(item_id))\n\n")

		if page != nil {
			sb.WriteString(fmt.Sprintf("    def find_all(self, limit: Optional[int] = None) -> List[%s]:\n", e.Name))
			sb.WriteString("        if limit is None:\n            limit = DEFAULT_PAGE_LIMIT\n")
			sb.WriteString("        if limit > MAX_PAGE_LIMIT:\n            limit = MAX_PAGE_LIMIT\n")
			sb.WriteString("        return list(self._items.values())[:limit]\n\n")
		} else {
			sb.WriteString(fmt.Sprintf("    def find_all(self) -> List[%s]:\n", e.Name))
			sb.WriteString("        return list(self._items.values())\n\n")
		}

		sb.WriteString("    def delete(self, item_id: str) -> bool:\n")
		sb.WriteString("        if str(item_id) in self._items:\n")
		sb.WriteString("            del self._items[str(item_id)]\n")
		sb.WriteString("            return True\n")
		sb.WriteString("        return False\n\n")
	}

	return sb.String()
}

func emitMainPy(entities []emitterkit.EntityDecl, actions []emitterkit.ActionDecl) string {
	var sb strings.Builder
	sb.WriteString(`# FastAPI Application
try:
    from fastapi import FastAPI, HTTPException
except ImportError:
    class FastAPI:
        def __init__(self, title="FastAPI"):
            self.title = title
            self.routes = []
        def post(self, path):
            def decorator(f):
                self.routes.append(("POST", path, f))
                return f
            return decorator
        def get(self, path):
            def decorator(f):
                self.routes.append(("GET", path, f))
                return f
            return decorator

from models import *
from repository import *

app = FastAPI(title="Foundation Service")

`)

	for _, e := range entities {
		sb.WriteString(fmt.Sprintf("%s_repo = %sRepository()\n", strings.ToLower(e.Name), e.Name))
	}
	sb.WriteString("\n")

	sb.WriteString(`@app.get("/health")
def health_check():
    return {"status": "ok"}

`)

	for _, a := range actions {
		path := fmt.Sprintf("/api/%s", strings.ToLower(a.Name))
		sb.WriteString(fmt.Sprintf("@app.post(%q)\n", path))
		sb.WriteString(fmt.Sprintf("def handle_%s(payload: dict):\n", strings.ToLower(a.Name)))
		sb.WriteString(fmt.Sprintf("    return {\"action\": %q, \"received\": payload}\n\n", a.Name))
	}

	return sb.String()
}

func emitTestAppPy(entities []emitterkit.EntityDecl, actions []emitterkit.ActionDecl) string {
	var sb strings.Builder
	sb.WriteString(`import pytest
from models import *
from repository import *
from main import app, health_check

def test_health():
    res = health_check()
    assert res == {"status": "ok"}

`)

	for _, e := range entities {
		eLower := strings.ToLower(e.Name)
		sb.WriteString(fmt.Sprintf("def test_%s_repository_crud():\n", eLower))
		sb.WriteString(fmt.Sprintf("    repo = %sRepository()\n", e.Name))

		var kwargs []string
		for _, f := range e.Fields {
			switch f.Type {
			case "string", "uuid":
				kwargs = append(kwargs, fmt.Sprintf("%s='test-%s'", f.Name, f.Name))
			case "int", "int64":
				kwargs = append(kwargs, fmt.Sprintf("%s=100", f.Name))
			case "float":
				kwargs = append(kwargs, fmt.Sprintf("%s=9.99", f.Name))
			case "bool":
				kwargs = append(kwargs, fmt.Sprintf("%s=True", f.Name))
			default:
				kwargs = append(kwargs, fmt.Sprintf("%s='val'", f.Name))
			}
		}

		sb.WriteString(fmt.Sprintf("    entity = %s(%s)\n", e.Name, strings.Join(kwargs, ", ")))
		sb.WriteString("    saved = repo.save(entity)\n")
		sb.WriteString("    assert saved is not None\n\n")

		hasID := false
		for _, f := range e.Fields {
			if f.Name == "id" {
				hasID = true
				break
			}
		}
		if hasID {
			sb.WriteString(fmt.Sprintf("    found = repo.find_by_id('test-id')\n"))
			sb.WriteString("    assert found is not None\n")
			sb.WriteString("    all_items = repo.find_all()\n")
			sb.WriteString("    assert len(all_items) == 1\n")
			sb.WriteString("    assert repo.delete('test-id') is True\n")
			sb.WriteString("    assert repo.find_by_id('test-id') is None\n")
		}
		sb.WriteString("\n")
	}

	for _, a := range actions {
		sb.WriteString(fmt.Sprintf("def test_action_%s():\n", strings.ToLower(a.Name)))
		sb.WriteString(fmt.Sprintf("    from main import handle_%s\n", strings.ToLower(a.Name)))
		sb.WriteString(fmt.Sprintf("    res = handle_%s({'sample': 'data'})\n", strings.ToLower(a.Name)))
		sb.WriteString(fmt.Sprintf("    assert res['action'] == %q\n", a.Name))
		sb.WriteString("    assert res['received'] == {'sample': 'data'}\n\n")
	}

	return sb.String()
}

func pyType(fdnType string) string {
	switch fdnType {
	case "string", "uuid", "decimal", "timestamp":
		return "str"
	case "int", "int64":
		return "int"
	case "float":
		return "float"
	case "bool":
		return "bool"
	default:
		return "str"
	}
}

package arch

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/galihanggara68/foundation/pkg/compiler/internal/ir"
)

const LockFileName = "foundation.lock.json"

type LockSnapshot struct {
	Version    int               `json:"version"`
	Entities   []ir.EntityDecl   `json:"entities"`
	Migrations []MigrationFileIR `json:"migrations,omitempty"`
}

// BuildStoragePlan computes the PostgreSQL declarative schema.sql and diff-based sequential migrations
// against foundation.lock.json, honoring @renamed_from and rejecting unhinted destructive drops unless force=true.
func BuildStoragePlan(workspaceDir string, sem *ir.SemanticIR, bp *BuildProfile, force bool) (StoragePlanIR, *LockSnapshot, []ir.Diagnostic) {
	plan := StoragePlanIR{
		Dialect: bp.Storage.Dialect,
		Mode:    bp.Storage.Mode,
	}
	if plan.Dialect == "" {
		plan.Dialect = "postgres"
	}
	if plan.Mode == "" {
		plan.Mode = "declarative"
	}

	enumSet := make(map[string]bool)
	for _, en := range sem.Enums {
		enumSet[en.Name] = true
	}

	schemaSQL := generateDeclarativeSchemaSQL(sem.Entities, enumSet)
	if plan.Mode == "declarative" || plan.Mode == "both" {
		plan.SchemaSQL = schemaSQL
	}

	lockPath := filepath.Join(workspaceDir, LockFileName)
	var prevLock LockSnapshot
	hasPrevLock := false
	if raw, err := os.ReadFile(lockPath); err == nil {
		if uErr := json.Unmarshal(raw, &prevLock); uErr == nil {
			hasPrevLock = true
		}
	}

	nextLock := &LockSnapshot{
		Version:    1,
		Entities:   sem.Entities,
		Migrations: append([]MigrationFileIR(nil), prevLock.Migrations...),
	}

	if plan.Mode == "migrations" || plan.Mode == "both" {
		if !hasPrevLock || len(prevLock.Migrations) == 0 {
			if len(sem.Entities) > 0 {
				downSQL := generateDropAllTablesSQL(sem.Entities)
				mig := MigrationFileIR{
					Number:  1,
					Name:    "0001_initial",
					UpSQL:   schemaSQL,
					DownSQL: downSQL,
				}
				nextLock.Migrations = []MigrationFileIR{mig}
			}
		} else {
			upSQL, downSQL, diags := diffEntitiesSQL(prevLock.Entities, sem.Entities, enumSet, force)
			if len(diags) > 0 {
				return StoragePlanIR{}, nil, diags
			}
			if strings.TrimSpace(upSQL) != "" {
				nextNum := len(nextLock.Migrations) + 1
				mig := MigrationFileIR{
					Number:  nextNum,
					Name:    fmt.Sprintf("%04d_migration", nextNum),
					UpSQL:   upSQL,
					DownSQL: downSQL,
				}
				nextLock.Migrations = append(nextLock.Migrations, mig)
			}
		}
		plan.Migrations = nextLock.Migrations
	}

	return plan, nextLock, nil
}

// WriteLockFile persists foundation.lock.json deterministically when migrations or entities are tracked.
func WriteLockFile(workspaceDir string, lock *LockSnapshot) []ir.Diagnostic {
	if lock == nil {
		return nil
	}
	lockPath := filepath.Join(workspaceDir, LockFileName)
	b, err := json.MarshalIndent(lock, "", "  ")
	if err != nil {
		return []ir.Diagnostic{{
			Code:     "FDN0411",
			Severity: ir.SeverityError,
			Message:  fmt.Sprintf("failed to serialize %s: %v", LockFileName, err),
			Span:     ir.Span{File: LockFileName, Line: 1, Column: 1},
		}}
	}
	b = append(b, '\n')
	if err := os.WriteFile(lockPath, b, 0644); err != nil {
		return []ir.Diagnostic{{
			Code:     "FDN0411",
			Severity: ir.SeverityError,
			Message:  fmt.Sprintf("failed to write %s: %v", LockFileName, err),
			Span:     ir.Span{File: LockFileName, Line: 1, Column: 1},
		}}
	}
	return nil
}

func generateDeclarativeSchemaSQL(entities []ir.EntityDecl, enumSet map[string]bool) string {
	var sb strings.Builder
	sb.WriteString("-- Generated by Foundation Compiler (PostgreSQL DDL)\n\n")
	for _, ent := range entities {
		sb.WriteString(generateCreateTableSQL(ent, enumSet))
		sb.WriteString("\n")
	}
	return sb.String()
}

func generateCreateTableSQL(ent ir.EntityDecl, enumSet map[string]bool) string {
	tableName := ToSnakeCase(ent.Name)
	var sb strings.Builder
	sb.WriteString(fmt.Sprintf("CREATE TABLE %s (\n", tableName))
	var indexes []string
	for i, f := range ent.Fields {
		colDef := columnDefinitionSQL(f, enumSet)
		comma := ","
		if i == len(ent.Fields)-1 {
			comma = ""
		}
		sb.WriteString(fmt.Sprintf("  %s %s%s\n", f.Name, colDef, comma))
		if f.HasTrait("index") {
			indexes = append(indexes, fmt.Sprintf("CREATE INDEX idx_%s_%s ON %s (%s);\n", tableName, f.Name, tableName, f.Name))
		}
	}
	sb.WriteString(");\n")
	for _, idxSQL := range indexes {
		sb.WriteString(idxSQL)
	}
	return sb.String()
}

func generateDropAllTablesSQL(entities []ir.EntityDecl) string {
	var sb strings.Builder
	for i := len(entities) - 1; i >= 0; i-- {
		sb.WriteString(fmt.Sprintf("DROP TABLE IF EXISTS %s CASCADE;\n", ToSnakeCase(entities[i].Name)))
	}
	return sb.String()
}

func columnDefinitionSQL(f ir.FieldDecl, enumSet map[string]bool) string {
	var parts []string
	parts = append(parts, sqlColumnType(f, enumSet))

	isPK := f.HasTrait("pk")
	if isPK {
		parts = append(parts, "PRIMARY KEY")
	} else if !f.Optional {
		parts = append(parts, "NOT NULL")
	}

	if f.HasTrait("unique") {
		parts = append(parts, "UNIQUE")
	}

	if fkRef, ok := getFieldTraitArg(f, "fk"); ok {
		parts = append(parts, "REFERENCES "+formatFKTarget(fkRef))
	}

	if f.HasTrait("auto_now_add") {
		parts = append(parts, "DEFAULT NOW()")
	} else if f.HasTrait("version") && f.DefaultVal == "" {
		parts = append(parts, "DEFAULT 1")
	} else if f.DefaultVal != "" {
		parts = append(parts, "DEFAULT "+formatSQLDefault(f.DefaultVal, f.Type, enumSet))
	}

	return strings.Join(parts, " ")
}

func sqlColumnType(f ir.FieldDecl, enumSet map[string]bool) string {
	switch f.Type {
	case "uuid":
		return "UUID"
	case "string":
		return "TEXT"
	case "int":
		return "INTEGER"
	case "decimal":
		if f.TypeParams != "" {
			return fmt.Sprintf("NUMERIC(%s)", f.TypeParams)
		}
		return "NUMERIC(10, 2)"
	case "bool":
		return "BOOLEAN"
	case "timestamp":
		return "TIMESTAMPTZ"
	default:
		if enumSet[f.Type] {
			return "TEXT"
		}
		return "JSONB"
	}
}

func formatSQLDefault(val, fType string, enumSet map[string]bool) string {
	if strings.HasPrefix(val, ".") {
		return fmt.Sprintf("'%s'", strings.TrimPrefix(val, "."))
	}
	if fType == "string" || enumSet[fType] {
		return fmt.Sprintf("'%s'", strings.Trim(val, `"'`))
	}
	return val
}

func formatFKTarget(ref string) string {
	parts := strings.SplitN(ref, ".", 2)
	if len(parts) == 2 {
		return fmt.Sprintf("%s(%s)", ToSnakeCase(parts[0]), parts[1])
	}
	return ToSnakeCase(ref) + "(id)"
}

func diffEntitiesSQL(prevEntities, currEntities []ir.EntityDecl, enumSet map[string]bool, force bool) (string, string, []ir.Diagnostic) {
	var upSB, downSB strings.Builder
	var diags []ir.Diagnostic

	prevMap := make(map[string]ir.EntityDecl)
	for _, e := range prevEntities {
		prevMap[e.Name] = e
	}

	matchedPrevEntities := make(map[string]bool)

	for _, curr := range currEntities {
		tableName := ToSnakeCase(curr.Name)
		prevName := curr.Name
		if renamedFrom, ok := getTraitsArg(curr.Traits, "renamed_from"); ok {
			if _, exists := prevMap[renamedFrom]; exists {
				prevName = renamedFrom
			}
		}

		prev, exists := prevMap[prevName]
		if !exists {
			upSB.WriteString(generateCreateTableSQL(curr, enumSet))
			downSB.WriteString(fmt.Sprintf("DROP TABLE IF EXISTS %s CASCADE;\n", tableName))
			continue
		}
		matchedPrevEntities[prevName] = true

		if prevName != curr.Name {
			oldTable := ToSnakeCase(prevName)
			upSB.WriteString(fmt.Sprintf("ALTER TABLE %s RENAME TO %s;\n", oldTable, tableName))
			downSB.WriteString(fmt.Sprintf("ALTER TABLE %s RENAME TO %s;\n", tableName, oldTable))
		}

		prevFields := make(map[string]ir.FieldDecl)
		for _, pf := range prev.Fields {
			prevFields[pf.Name] = pf
		}
		matchedPrevFields := make(map[string]bool)

		for _, cf := range curr.Fields {
			if oldFieldName, ok := getFieldTraitArg(cf, "renamed_from"); ok {
				if pf, oldExists := prevFields[oldFieldName]; oldExists {
					matchedPrevFields[oldFieldName] = true
					upSB.WriteString(fmt.Sprintf("ALTER TABLE %s RENAME COLUMN %s TO %s;\n", tableName, oldFieldName, cf.Name))
					downSB.WriteString(fmt.Sprintf("ALTER TABLE %s RENAME COLUMN %s TO %s;\n", tableName, cf.Name, oldFieldName))
					diffColumnChangesSQL(tableName, pf, cf, enumSet, &upSB, &downSB)
					continue
				}
			}
			if pf, oldExists := prevFields[cf.Name]; oldExists {
				matchedPrevFields[cf.Name] = true
				diffColumnChangesSQL(tableName, pf, cf, enumSet, &upSB, &downSB)
				continue
			}
			// Added column
			colDef := columnDefinitionSQL(cf, enumSet)
			upSB.WriteString(fmt.Sprintf("ALTER TABLE %s ADD COLUMN %s %s;\n", tableName, cf.Name, colDef))
			downSB.WriteString(fmt.Sprintf("ALTER TABLE %s DROP COLUMN %s;\n", tableName, cf.Name))
			if cf.HasTrait("index") {
				upSB.WriteString(fmt.Sprintf("CREATE INDEX idx_%s_%s ON %s (%s);\n", tableName, cf.Name, tableName, cf.Name))
			}
		}

		// Check dropped columns
		for _, pf := range prev.Fields {
			if !matchedPrevFields[pf.Name] {
				if !force {
					diags = append(diags, ir.Diagnostic{
						Code:     "FDN0410",
						Severity: ir.SeverityError,
						Message:  fmt.Sprintf("destructive schema change: column %q on entity %q was removed without @renamed_from hint (use --force to allow DROP COLUMN)", pf.Name, curr.Name),
						Span:     curr.Span,
					})
				} else {
					colDef := columnDefinitionSQL(pf, enumSet)
					upSB.WriteString(fmt.Sprintf("ALTER TABLE %s DROP COLUMN %s;\n", tableName, pf.Name))
					downSB.WriteString(fmt.Sprintf("ALTER TABLE %s ADD COLUMN %s %s;\n", tableName, pf.Name, colDef))
				}
			}
		}
	}

	// Check dropped entities
	for _, prev := range prevEntities {
		if !matchedPrevEntities[prev.Name] {
			if !force {
				diags = append(diags, ir.Diagnostic{
					Code:     "FDN0410",
					Severity: ir.SeverityError,
					Message:  fmt.Sprintf("destructive schema change: entity %q was removed without @renamed_from hint (use --force to allow DROP TABLE)", prev.Name),
					Span:     prev.Span,
				})
			} else {
				tableName := ToSnakeCase(prev.Name)
				upSB.WriteString(fmt.Sprintf("DROP TABLE IF EXISTS %s CASCADE;\n", tableName))
				downSB.WriteString(generateCreateTableSQL(prev, enumSet))
			}
		}
	}

	return upSB.String(), downSB.String(), diags
}

func diffColumnChangesSQL(tableName string, prevField, currField ir.FieldDecl, enumSet map[string]bool, upSB, downSB *strings.Builder) {
	prevType := sqlColumnType(prevField, enumSet)
	currType := sqlColumnType(currField, enumSet)
	if prevType != currType {
		upSB.WriteString(fmt.Sprintf("ALTER TABLE %s ALTER COLUMN %s TYPE %s;\n", tableName, currField.Name, currType))
		downSB.WriteString(fmt.Sprintf("ALTER TABLE %s ALTER COLUMN %s TYPE %s;\n", tableName, currField.Name, prevType))
	}
	if prevField.Optional != currField.Optional && !currField.HasTrait("pk") {
		if currField.Optional {
			upSB.WriteString(fmt.Sprintf("ALTER TABLE %s ALTER COLUMN %s DROP NOT NULL;\n", tableName, currField.Name))
			downSB.WriteString(fmt.Sprintf("ALTER TABLE %s ALTER COLUMN %s SET NOT NULL;\n", tableName, currField.Name))
		} else {
			upSB.WriteString(fmt.Sprintf("ALTER TABLE %s ALTER COLUMN %s SET NOT NULL;\n", tableName, currField.Name))
			downSB.WriteString(fmt.Sprintf("ALTER TABLE %s ALTER COLUMN %s DROP NOT NULL;\n", tableName, currField.Name))
		}
	}
	if prevField.DefaultVal != currField.DefaultVal {
		if currField.DefaultVal != "" {
			upSB.WriteString(fmt.Sprintf("ALTER TABLE %s ALTER COLUMN %s SET DEFAULT %s;\n", tableName, currField.Name, formatSQLDefault(currField.DefaultVal, currField.Type, enumSet)))
		} else {
			upSB.WriteString(fmt.Sprintf("ALTER TABLE %s ALTER COLUMN %s DROP DEFAULT;\n", tableName, currField.Name))
		}
		if prevField.DefaultVal != "" {
			downSB.WriteString(fmt.Sprintf("ALTER TABLE %s ALTER COLUMN %s SET DEFAULT %s;\n", tableName, currField.Name, formatSQLDefault(prevField.DefaultVal, prevField.Type, enumSet)))
		} else {
			downSB.WriteString(fmt.Sprintf("ALTER TABLE %s ALTER COLUMN %s DROP DEFAULT;\n", tableName, currField.Name))
		}
	}
}

func getFieldTraitArg(f ir.FieldDecl, name string) (string, bool) {
	return getTraitsArg(f.Traits, name)
}

func getTraitsArg(traits []ir.TraitDecl, name string) (string, bool) {
	for _, tr := range traits {
		if tr.Name == name {
			if v, ok := tr.Args["_"]; ok {
				return v, true
			}
			var keys []string
			for k := range tr.Args {
				keys = append(keys, k)
			}
			sort.Strings(keys)
			if len(keys) > 0 {
				return tr.Args[keys[0]], true
			}
		}
	}
	return "", false
}

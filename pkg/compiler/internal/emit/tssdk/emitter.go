package tssdk

import (
	"encoding/json"
	"fmt"

	"github.com/galihanggara68/foundation/pkg/compiler/internal/arch"
	"github.com/galihanggara68/foundation/pkg/compiler/internal/emit"
	"github.com/galihanggara68/foundation/pkg/compiler/internal/ir"
)

// Emitter generates a standalone, zero-external-dependency TypeScript client SDK package.
type Emitter struct{}

func (Emitter) Emit(archIR *arch.ArchitectureIR) (emit.Emission, []ir.Diagnostic) {
	files := make(map[string][]byte)

	pkgJSON, _ := json.MarshalIndent(map[string]interface{}{
		"name":        fmt.Sprintf("%s-client", archIR.TargetName),
		"version":     "0.1.0",
		"type":        "module",
		"main":        "./index.ts",
		"types":       "./index.ts",
		"description": "Zero-dependency strongly-typed TypeScript API client generated by Foundation",
	}, "", "  ")
	files["package.json"] = append(pkgJSON, '\n')

	files["types.ts"] = []byte(emitTypes(archIR))
	files["errors.ts"] = []byte(emitErrors(archIR))
	files["client.ts"] = []byte(emitClient(archIR))
	files["index.ts"] = []byte(`export * from "./types.ts";
export * from "./errors.ts";
export * from "./client.ts";
`)

	return emit.Emission{
		TrackedFiles: files,
		StubFiles:    make(map[string][]byte),
	}, nil
}
